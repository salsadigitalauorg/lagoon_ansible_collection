class TestCheckMode(unittest.TestCase):
    """Each case runs the same scenario twice -- once for real, once under
    check mode -- and asserts the check-mode run makes zero mutation calls
    while reporting the same changed flag.
    """

    def test_check_mode_create(self):
        """Create is the one transition whose diff cannot match exactly: a
        real run re-reads and therefore reports fields the server
        defaulted, which check mode has no way to predict. What must hold
        is that check mode makes no mutation, agrees on changed, and
        predicts a subset the real run does not contradict.
        """
        params = dict(git_url='git@github.com:example/my-project.git',
                      production_environment='main')

        real_result, real_execute = _run(
            _make_module(**params), [None, _existing()],
            {'addProject': {'id': 42}})
        check_result, check_execute = _run(
            _make_module(check_mode=True, **params), [None])

        self.assertEqual(len(real_execute.mutations), 1)
        self.assertEqual(check_execute.mutations, [])
        self.assertEqual(check_result['changed'], real_result['changed'])
        self.assertIsNone(check_result['diff']['before'])
        self.assertIsNone(real_result['diff']['before'])

        real_after = real_result['diff']['after']
        for field, value in check_result['diff']['after'].items():
            self.assertIn(field, real_after)
            self.assertEqual(
                real_after[field], value,
                "check mode predicted %s=%r but the real run reported %r"
                % (field, value, real_after.get(field)))

    def test_check_mode_update(self):
        real_result, real_execute = _run(
            _make_module(auto_idle=0),
            [_existing(), _existing(autoIdle=0)],
            {'updateProject': {'id': 42}})
        check_result, check_execute = _run(
            _make_module(auto_idle=0, check_mode=True), [_existing()])

        self.assertEqual(len(real_execute.mutations), 1)
        self.assertEqual(check_execute.mutations, [])
        self.assertEqual(check_result['changed'], real_result['changed'])
        self.assertEqual(check_result['diff'], real_result['diff'])

    def test_check_mode_delete(self):
        real_result, real_execute = _run(
            _make_module(state='absent'), [_existing()],
            {'deleteProject': 'success'})
        check_result, check_execute = _run(
            _make_module(state='absent', check_mode=True), [_existing()])

        self.assertEqual(len(real_execute.mutations), 1)
        self.assertEqual(check_execute.mutations, [])
        self.assertEqual(check_result['changed'], real_result['changed'])
        self.assertEqual(check_result['diff'], real_result['diff'])


