_ARGSPEC = argument_spec()

_MODULE_PATH = (
    'ansible_collections.salsadigitalauorg.lagoon.plugins.modules.project')

_EXISTING = {
    'id': 42,
    'name': 'my-project',
    'gitUrl': 'git@github.com:example/my-project.git',
    'productionEnvironment': 'main',
    'autoIdle': 1,
    'openshift': {'id': 2},
    'kubernetes': None,
    'autogeneratedRouteConfig': {
        'enabled': True,
        'allowPullRequests': False,
        'prefixes': [],
        'disableRequestVerification': False,
        'pathRoutes': [],
    },
}


def _existing(**overrides):
    record = dict(_EXISTING)
    record['autogeneratedRouteConfig'] = dict(
        _EXISTING['autogeneratedRouteConfig'])
    record.update(overrides)
    return record


def _make_module(state='present', check_mode=False, **params):
    """A minimal stand-in for AnsibleModule exposing only what
    run_module() reads, so this proves the module depends on nothing else
    from AnsibleModule itself.
    """
    module = MagicMock()
    module.params = {
        'lagoon_api_token': 'explicit-token',
        'lagoon_api_endpoint': 'https://api.lagoon.example.test/graphql',
        'validate_certs': True,
        'state': state,
    }
    # Every argspec option defaults to None, exactly as AnsibleModule
    # would present an unsupplied option.
    for option in _ARGSPEC:
        module.params.setdefault(option, None)
    module.params['name'] = 'my-project'
    module.params.update(params)
    module.check_mode = check_mode
    return module


class _Execute:
    """Queue-backed stand-in for LagoonClient.execute.

    Records every (document, variables) pair, and returns responses in
    order. Reads are matched by operation name so a test only has to
    supply the read results it cares about.
    """

    def __init__(self, read_results, mutation_result=None):
        self._read_results = list(read_results)
        self._mutation_result = mutation_result or {}
        self.calls = []

    def __call__(self, document, variables=None):
        self.calls.append((document, variables or {}))
        if document.startswith('query projectByName'):
            result = self._read_results.pop(0)
            return {'projectByName': result}
        return self._mutation_result

    @property
    def mutations(self):
        return [(d, v) for d, v in self.calls
                if not d.startswith('query projectByName')]

    def mutation_named(self, name):
        matches = [(d, v) for d, v in self.mutations
                   if d.startswith('mutation %s(' % name)]
        return matches

    @property
    def read_documents(self):
        return [d for d, _v in self.calls
                if d.startswith('query projectByName')]


def _run(module, read_results, mutation_result=None):
    execute = _Execute(read_results, mutation_result)
    with patch('%s.LagoonClient.execute' % _MODULE_PATH, new=execute):
        result = run_module(module)
    return result, execute


class TestCreate(unittest.TestCase):

    def test_create_calls_add_project_with_wire_names(self):
        module = _make_module(
            git_url='git@github.com:example/my-project.git',
            production_environment='main')

        result, execute = _run(
            module, [None, _existing()], {'addProject': {'id': 42}})

        self.assertTrue(result['changed'])
        added = execute.mutation_named('addProject')
        self.assertEqual(len(added), 1)
        payload = added[0][1]['input']
        self.assertEqual(payload['name'], 'my-project')
        self.assertEqual(
            payload['gitUrl'], 'git@github.com:example/my-project.git')
        self.assertEqual(payload['productionEnvironment'], 'main')

    def test_create_missing_git_url_raises_naming_the_option(self):
        """P3-D15: enforced on the create path, not via argspec required.
        The argspec assertion below is the half that would silently pass
        if someone "fixed" this by marking git_url required instead.
        """
        module = _make_module(production_environment='main')

        with self.assertRaises(LagoonConfigError) as ctx:
            _run(module, [None])

        self.assertIn('git_url', str(ctx.exception))
        self.assertNotIn(
            'required', _ARGSPEC['git_url'],
            "git_url must not be argspec-required -- the same argspec "
            "also serves update and delete")

    def test_create_missing_both_non_null_fields_names_both(self):
        module = _make_module()

        with self.assertRaises(LagoonConfigError) as ctx:
            _run(module, [None])

        message = str(ctx.exception)
        self.assertIn('git_url', message)
        self.assertIn('production_environment', message)

    def test_create_makes_no_mutation_call_when_required_missing(self):
        module = _make_module(production_environment='main')
        execute = _Execute([None])

        with patch('%s.LagoonClient.execute' % _MODULE_PATH, new=execute):
            with self.assertRaises(LagoonConfigError):
                run_module(module)

        self.assertEqual(execute.mutations, [])

    def test_create_does_not_send_update_only_fields(self):
        module = _make_module(
            git_url='git@github.com:example/my-project.git',
            production_environment='main',
            restrictions=['NO_TASKS'])

        _result, execute = _run(
            module, [None, _existing()], {'addProject': {'id': 42}})

        payload = execute.mutation_named('addProject')[0][1]['input']
        self.assertNotIn(
            'restrictions', payload,
            "restrictions is only on UpdateProjectPatchInput -- sending "
            "it to addProject would be rejected by the API")


class TestUpdate(unittest.TestCase):

    def test_update_builds_nested_id_patch_shape(self):
        """The {id, patch} wrapping is the single most regression-prone
        shape in this module: addProject is flat, updateProject is not.
        Asserted on the exact variables dict so flattening it back out
        cannot pass.
        """
        module = _make_module(auto_idle=0)

        result, execute = _run(
            module,
            [_existing(), _existing(autoIdle=0)],
            {'updateProject': {'id': 42}})

        self.assertTrue(result['changed'])
        updated = execute.mutation_named('updateProject')
        self.assertEqual(len(updated), 1)
        self.assertEqual(
            updated[0][1],
            {'input': {'id': 42, 'patch': {'autoIdle': 0}}})

    def test_update_of_hop_field_uses_flat_input_name(self):
        """openshift is Int on input but an Openshift object on output --
        the patch must carry the flat name, not the hop's shape.
        """
        module = _make_module(openshift=7)

        _result, execute = _run(
            module,
            [_existing(), _existing(openshift={'id': 7})],
            {'updateProject': {'id': 42}})

        patch_payload = execute.mutation_named(
            'updateProject')[0][1]['input']['patch']
        self.assertEqual(patch_payload, {'openshift': 7})

    def test_update_of_autogenerated_route_config_field(self):
        """autogeneratedRoutes reads from the ARC hop's `enabled` leaf but
        is patched under its own input name.
        """
        module = _make_module(autogenerated_routes=False)

        _result, execute = _run(
            module,
            [_existing(),
             _existing(autogeneratedRouteConfig=dict(
                 _EXISTING['autogeneratedRouteConfig'], enabled=False))],
            {'updateProject': {'id': 42}})

        patch_payload = execute.mutation_named(
            'updateProject')[0][1]['input']['patch']
        self.assertEqual(patch_payload, {'autogeneratedRoutes': False})

    def test_update_of_path_routes_carries_list_of_dicts(self):
        desired = [{'from_service': 'nginx', 'to_service': 'api',
                    'path': '/api'}]
        module = _make_module(autogenerated_path_routes=desired)

        _result, execute = _run(
            module,
            [_existing(),
             _existing(autogeneratedRouteConfig=dict(
                 _EXISTING['autogeneratedRouteConfig'],
                 pathRoutes=[{'fromService': 'nginx', 'toService': 'api',
                              'path': '/api'}]))],
            {'updateProject': {'id': 42}})

        patch_payload = execute.mutation_named(
            'updateProject')[0][1]['input']['patch']
        self.assertEqual(
            patch_payload, {'autogeneratedPathRoutes': desired})

    def test_path_routes_unchanged_is_a_noop(self):
        """The read flattens pathRoutes into the argspec's own key names,
        so an unchanged value must compare structurally equal and report
        no change -- otherwise every run against a project with path
        routes would report changed forever.
        """
        current = _existing(autogeneratedRouteConfig=dict(
            _EXISTING['autogeneratedRouteConfig'],
            pathRoutes=[{'fromService': 'nginx', 'toService': 'api',
                         'path': '/api'}]))
        module = _make_module(autogenerated_path_routes=[
            {'from_service': 'nginx', 'to_service': 'api', 'path': '/api'}])

        result, execute = _run(module, [current])

        self.assertFalse(result['changed'])
        self.assertEqual(execute.mutations, [])


