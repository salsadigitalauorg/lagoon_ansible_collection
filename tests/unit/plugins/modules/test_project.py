"""Unit tests for the project module -- resource.py's golden target.

Every test drives ``run_module`` directly against a params-bearing stand-in
for ``AnsibleModule``, with ``LagoonClient.execute`` mocked at the transport
boundary. No action shim is constructed anywhere in this file: a module
handed an explicit ``lagoon_api_token`` must be fully functional on its own.

``execute`` is driven by a queue of responses rather than a single return
value, because the engine re-reads after every real mutation -- a test that
returned one fixed response would not distinguish post-mutation state from
the locally computed desired state.
"""

from __future__ import (absolute_import, division, print_function)
